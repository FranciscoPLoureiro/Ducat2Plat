// Generates web/src/lib/set-slots.ts — a static map of Prime set url_name ->
// trade slots (a set trades as its parts, so a dual weapon like Aksomati Prime
// occupies 6 slots: barrel x2 + receiver x2 + blueprint + link).
//
// Part quantities live only in warframe.market's per-item detail. To avoid
// fetching every part, we only fetch parts of sets whose ducat value exceeds
// the sum of its distinct parts' ducats (i.e. some part is needed 2+ times) —
// every other set is simply its distinct-part count. Re-run after new Prime
// sets release:  node worker/scripts/gen-set-slots.mjs
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const V2 = "https://api.warframe.market/v2";
const UA = "Ducat2Plat/1.0 (+https://github.com/FranciscoPLoureiro/Ducat2Plat)";
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function get(url) {
  const res = await fetch(url, { headers: { Accept: "application/json", "User-Agent": UA } });
  if (!res.ok) throw new Error(`${res.status} ${url}`);
  return (await res.json()).data;
}

async function quantityInSet(slug) {
  await sleep(340);
  const d = await get(`${V2}/items/${slug}`);
  return typeof d.quantityInSet === "number" ? d.quantityInSet : 1;
}

const items = await get(`${V2}/items`);
const ducats = new Map();
const urls = [];
for (const it of items) {
  if (typeof it.ducats === "number") {
    ducats.set(it.slug, it.ducats);
    urls.push(it.slug);
  }
}

const sets = urls.filter((u) => u.endsWith("_set"));
const partsOf = (s) => {
  const prefix = s.slice(0, -4) + "_";
  return urls.filter((u) => u !== s && !u.endsWith("_set") && u.startsWith(prefix));
};

const out = {};
let fetched = 0;
for (const s of sets) {
  const parts = partsOf(s);
  if (parts.length === 0) continue;
  const distinctSum = parts.reduce((a, p) => a + (ducats.get(p) || 0), 0);
  const setDucats = ducats.get(s) || 0;
  let slots;
  if (setDucats > distinctSum) {
    // some part is needed 2+ times — fetch exact quantities
    let sum = 0;
    for (const p of parts) sum += await quantityInSet(p);
    slots = sum;
    fetched += parts.length;
    console.log(`  ${s}: ${parts.length} parts -> ${slots} slots (fetched; set ${setDucats}d > parts ${distinctSum}d)`);
  } else {
    slots = parts.length;
  }
  if (slots > 1) out[s] = slots;
}

const sorted = Object.fromEntries(Object.entries(out).sort(([a], [b]) => a.localeCompare(b)));
const header = `// AUTO-GENERATED by worker/scripts/gen-set-slots.mjs — do not edit by hand.\n// Prime set url_name -> in-game trade slots (parts including multiples).\n`;
const body = `export const SET_SLOTS: Record<string, number> = ${JSON.stringify(sorted, null, 2)};\n`;
const target = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "web", "src", "lib", "set-slots.ts");
writeFileSync(target, header + body, "utf8");
console.log(`\nWrote ${Object.keys(sorted).length} sets to set-slots.ts (${fetched} part detail fetches).`);
