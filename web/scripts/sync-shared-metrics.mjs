// Copies shared/metrics.ts into web/src/lib/metrics.ts with a generated
// header. web/ cannot import ../shared directly: Turbopack resolves outside
// the project root inconsistently, and the Vercel build (root directory =
// web/) does not upload ../shared at all — so the committed copy is what
// production builds from, and this script + the metrics-sync test keep it
// from drifting.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const source = join(here, "..", "..", "shared", "metrics.ts");
const target = join(here, "..", "src", "lib", "metrics.ts");

if (!existsSync(source)) {
  // Vercel builds only upload web/ — the committed copy is already in sync
  // (CI enforces it), so this is a safe no-op there.
  console.log("sync-shared-metrics: ../shared not present (Vercel build) — skipping");
  process.exit(0);
}

const HEADER = `// AUTO-GENERATED from shared/metrics.ts — DO NOT EDIT THIS FILE.
// Edit shared/metrics.ts instead, then run \`npm run sync-shared\` in web/.
// The metrics-sync test fails CI if this copy drifts from the source.
`;

const body = readFileSync(source, "utf8");
writeFileSync(target, HEADER + body, "utf8");
console.log("sync-shared-metrics: web/src/lib/metrics.ts regenerated");
